"""
Chat Routes
API endpoints for chat functionality
"""
import json
import logging

from fastapi import APIRouter, HTTPException
from fastapi.responses import StreamingResponse

from controllers.chat_controller import (
    chat_controller,
    ChatRequest,
    ChatResponse,
    StatusResponse
)

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/chat", tags=["Chat"])


@router.get("/status", response_model=StatusResponse)
async def get_status():
    """
    Get the current status of the LLM service.

    Returns information about whether the service is ready and the status
    of individual components (embedding model, vector store, LLM, etc.)
    """
    try:
        return chat_controller.get_status()
    except (RuntimeError, OSError, ValueError) as e:
        logger.error("Error getting status: %s", e)
        raise HTTPException(status_code=500, detail=str(e)) from e


@router.post("/generate", response_model=ChatResponse)
async def generate_response(request: ChatRequest):
    """
    Generate a complete response for a user message.

    This endpoint retrieves relevant documents, processes them through the
    RAG chain, and returns the complete response.
    """
    try:
        return await chat_controller.generate_response(request)
    except RuntimeError as e:
        raise HTTPException(status_code=503, detail=str(e)) from e
    except (OSError, ValueError) as e:
        logger.error("Error generating response: %s", e)
        raise HTTPException(status_code=500, detail=str(e)) from e


@router.post("/stream")
async def stream_response(request: ChatRequest):
    """
    Stream a response for a user message.

    This endpoint returns a streaming response where tokens are sent
    as Server-Sent Events (SSE) as they are generated by the LLM.
    """
    try:
        async def event_generator():
            try:
                async for chunk in chat_controller.stream_response(request):
                    # Send as SSE format
                    yield f"data: {json.dumps({'content': chunk})}\n\n"
                # Send completion signal
                yield f"data: {json.dumps({'done': True})}\n\n"
            except (RuntimeError, OSError, ValueError) as e:
                logger.error("Error in stream generator: %s", e)
                yield f"data: {json.dumps({'error': str(e)})}\n\n"

        return StreamingResponse(
            event_generator(),
            media_type="text/event-stream",
            headers={
                "Cache-Control": "no-cache",
                "Connection": "keep-alive",
                "X-Accel-Buffering": "no"
            }
        )
    except RuntimeError as e:
        raise HTTPException(status_code=503, detail=str(e)) from e
    except (OSError, ValueError) as e:
        logger.error("Error starting stream: %s", e)
        raise HTTPException(status_code=500, detail=str(e)) from e


@router.get("/health")
async def health_check():
    """
    Simple health check endpoint.

    Returns basic health status without detailed component information.
    """
    status = chat_controller.get_status()
    return {
        "status": "healthy" if status.is_loaded else "initializing",
        "ready": status.is_loaded
    }
